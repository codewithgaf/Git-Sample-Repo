# Define two numbers
a = 10
b = 3

# Perform arithmetic operations
addition = a + b        # 13
subtraction = a - b     # 7
multiplication = a * b  # 30
division = a / b        # 3.3333... (Always returns a float)
floor_division = a // b # 3 (Divides and rounds down to the nearest whole number)
modulus = a % b         # 1 (Returns the remainder of the division)
exponent = a ** b       # 1000 (10 raised to the power of 3)

# Print the results
print("Addition (+):", addition)
print("Subtraction (-):", subtraction)
print("Multiplication (*):", multiplication)
print("Division (/):", division)
print("Floor Division (//):", floor_division)
print("Modulus (%):", modulus)
print("Exponent (**):", exponent)

# Display message
print("/n Hello World!")